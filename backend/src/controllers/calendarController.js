import CalendarEvent from "../models/CalendarEvent.js";
import TimelineEvent from "../models/TimelineEvent.js";
import mongoose from "mongoose";

/**
 * Fetch calendar events.
 * Dynamically aggregates custom events + past completed milestones from TimelineEvent.
 */
export const getCalendarEvents = async (req, res) => {
  try {
    const studentId = req.user.id;
    const { start, end } = req.query;

    const dateQuery = {};
    if (start) dateQuery.$gte = new Date(start);
    if (end) dateQuery.$lte = new Date(end);

    const query = { studentId };
    if (Object.keys(dateQuery).length > 0) {
      query.date = dateQuery;
    }

    // 1. Fetch custom events
    const customEvents = await CalendarEvent.find(query)
      .populate("courseId", "title thumbnail")
      .populate("moduleId", "title")
      .sort({ date: 1, startTime: 1 });

    // 2. Fetch timeline milestones within range
    const timelineQuery = { studentId };
    if (start || end) {
      timelineQuery.timestamp = {};
      if (start) timelineQuery.timestamp.$gte = new Date(start);
      if (end) timelineQuery.timestamp.$lte = new Date(end);
    }

    const milestones = await TimelineEvent.find(timelineQuery)
      .populate("courseId", "title thumbnail")
      .populate("moduleId", "title")
      .sort({ timestamp: 1 });

    // Map milestones to auto-generated Completed calendar events
    const autoEvents = milestones.map((event) => {
      // Map eventTypes to calendar eventTypes
      let calendarType = "study";
      if (event.eventType === "notes_read") calendarType = "notes";
      if (event.eventType === "quiz_complete") calendarType = "quiz";

      return {
        _id: `auto-${event._id}`,
        studentId: event.studentId,
        courseId: event.courseId,
        moduleId: event.moduleId,
        eventType: calendarType,
        title: event.title,
        description: event.description,
        date: event.timestamp,
        startTime: new Date(event.timestamp).toLocaleTimeString(undefined, { hour: "2-digit", minute: "2-digit", hour12: false }),
        endTime: new Date(event.timestamp).toLocaleTimeString(undefined, { hour: "2-digit", minute: "2-digit", hour12: false }),
        priority: "low",
        status: "completed",
        isAutoGenerated: true
      };
    });

    // Merge both
    const allEvents = [...customEvents, ...autoEvents];

    res.status(200).json(allEvents);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

/**
 * Add custom calendar event.
 */
export const addCalendarEvent = async (req, res) => {
  try {
    const studentId = req.user.id;
    const { courseId, moduleId, eventType, title, description, date, startTime, endTime, priority } = req.body;

    const event = await CalendarEvent.create({
      studentId,
      courseId: courseId || null,
      moduleId: moduleId || null,
      eventType: eventType || "study",
      title,
      description,
      date: new Date(date),
      startTime: startTime || "09:00",
      endTime: endTime || "10:00",
      priority: priority || "medium",
      status: "upcoming",
      isAutoGenerated: false
    });

    res.status(201).json({ message: "Calendar event scheduled successfully", event });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

/**
 * Update custom calendar event.
 */
export const updateCalendarEvent = async (req, res) => {
  try {
    const studentId = req.user.id;
    const { id } = req.params;
    const { title, description, date, startTime, endTime, priority, status } = req.body;

    const event = await CalendarEvent.findOneAndUpdate(
      { _id: id, studentId, isAutoGenerated: false },
      { title, description, date: date ? new Date(date) : undefined, startTime, endTime, priority, status },
      { new: true }
    );

    if (!event) {
      return res.status(404).json({ message: "Calendar event not found or is auto-generated" });
    }

    res.status(200).json({ message: "Calendar event updated successfully", event });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

/**
 * Delete custom calendar event.
 */
export const deleteCalendarEvent = async (req, res) => {
  try {
    const studentId = req.user.id;
    const { id } = req.params;

    const deleted = await CalendarEvent.findOneAndDelete({ _id: id, studentId, isAutoGenerated: false });
    if (!deleted) {
      return res.status(404).json({ message: "Calendar event not found or is auto-generated" });
    }

    res.status(200).json({ message: "Calendar event deleted successfully" });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};
