import mongoose from "mongoose";

const calendarEventSchema = new mongoose.Schema(
  {
    studentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    courseId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Course",
    },
    moduleId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Module",
    },
    eventType: {
      type: String,
      enum: ["study", "quiz", "notes", "assignment", "revision", "live_class", "reminder"],
      default: "study",
    },
    title: {
      type: String,
      required: true,
    },
    description: {
      type: String,
      default: "",
    },
    date: {
      type: Date,
      required: true,
    },
    startTime: {
      type: String,
      default: "09:00", // Format: "HH:MM"
    },
    endTime: {
      type: String,
      default: "10:00", // Format: "HH:MM"
    },
    priority: {
      type: String,
      enum: ["low", "medium", "high"],
      default: "medium",
    },
    status: {
      type: String,
      enum: ["upcoming", "in_progress", "completed", "missed", "cancelled"],
      default: "upcoming",
    },
    isAutoGenerated: {
      type: Boolean,
      default: false,
    }
  },
  {
    timestamps: true,
  }
);

calendarEventSchema.index({ studentId: 1, date: 1 });

const CalendarEvent = mongoose.models.CalendarEvent || mongoose.model("CalendarEvent", calendarEventSchema);
export default CalendarEvent;
